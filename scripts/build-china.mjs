// Generates src/content/china-map.ts (China border + neighbouring land as SVG paths)
// and prints the Mercator parameters scripts/build-china-satellite.py needs.
// Source: Natural Earth via `world-atlas` (public domain). Run: node scripts/build-china.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoMercator, geoPath } from "d3-geo";
import { feature } from "topojson-client";

export const W = 700;
export const H = 560;
const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-50m.json", "utf8"));
const countries = feature(topo, topo.objects.countries).features;
const cn = countries.find((f) => f.properties.name === "China");
if (!cn) throw new Error("China not found");

const projection = geoMercator().fitExtent([[40, 40], [W - 40, H - 40]], cn);
const path = geoPath(projection).digits(1);
const clip = geoMercator().scale(projection.scale()).translate(projection.translate()).clipExtent([[-20, -20], [W + 20, H + 20]]);
const cpath = geoPath(clip).digits(1);
const land = countries.map((f) => cpath(f)).filter(Boolean);
const china = path(cn);

const out = `// Generated by scripts/build-china.mjs from Natural Earth (public domain). Do not edit by hand.
export const cnSize = { width: ${W}, height: ${H} };
export const cnLand: string[] = ${JSON.stringify(land)};
export const cnBorder = ${JSON.stringify(china)};
`;
writeFileSync("src/content/china-map.ts", out);
console.log(JSON.stringify({ s: projection.scale(), t: projection.translate(), W, H, bytes: out.length }));

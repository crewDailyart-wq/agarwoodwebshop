// Generates src/content/vietnam-map.ts (Vietnam border + neighbouring land as SVG paths)
// and prints the Mercator parameters scripts/build-vietnam-satellite.py needs.
// Source: Natural Earth via `world-atlas` (public domain). Run: node scripts/build-vietnam.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoMercator, geoPath } from "d3-geo";
import { feature } from "topojson-client";

export const W = 600;
export const H = 860;
const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-50m.json", "utf8"));
const countries = feature(topo, topo.objects.countries).features;
const vn = countries.find((f) => f.properties.name === "Vietnam");
if (!vn) throw new Error("Vietnam not found");

const projection = geoMercator().fitExtent([[70, 60], [W - 70, H - 60]], vn);
const path = geoPath(projection).digits(1);
const clip = geoMercator().scale(projection.scale()).translate(projection.translate()).clipExtent([[-20, -20], [W + 20, H + 20]]);
const cpath = geoPath(clip).digits(1);
const land = countries.map((f) => cpath(f)).filter(Boolean);
const vietnam = path(vn);

const out = `// Generated by scripts/build-vietnam.mjs from Natural Earth (public domain). Do not edit by hand.
export const vnSize = { width: ${W}, height: ${H} };
export const vnLand: string[] = ${JSON.stringify(land)};
export const vnBorder = ${JSON.stringify(vietnam)};
`;
writeFileSync("src/content/vietnam-map.ts", out);
console.log(JSON.stringify({ s: projection.scale(), t: projection.translate(), W, H, bytes: out.length }));

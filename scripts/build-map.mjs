// Generates src/content/asia-map.ts: SVG path data for the agarwood atlas.
// Source: Natural Earth via the `world-atlas` package (public domain).
// Run: node scripts/build-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoMercator, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const W = 1000;
const H = 640;
const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-50m.json", "utf8"));
const countries = feature(topo, topo.objects.countries).features;

const highlight = new Set([
  "India", "Bangladesh", "Sri Lanka", "Myanmar", "Thailand", "Laos", "Cambodia",
  "Vietnam", "China", "Malaysia", "Singapore", "Brunei", "Indonesia", "Philippines",
  "Papua New Guinea",
]);

const projection = geoMercator()
  .fitExtent([[0, 0], [W, H]], { type: "MultiPoint", coordinates: [[64, 33], [156, -13]] })
  .clipExtent([[-10, -10], [W + 10, H + 10]]);
const path = geoPath(projection).digits(0);

const land = [];
const regions = [];
const found = new Set();
for (const f of countries) {
  const d = path(f);
  if (!d) continue;
  if (highlight.has(f.properties.name)) {
    regions.push({ name: f.properties.name, d });
    found.add(f.properties.name);
  } else land.push(d);
}
const missing = [...highlight].filter((n) => !found.has(n));
if (missing.length) throw new Error("Missing countries: " + missing.join(", "));

const markers = [
  ["Bangladesh", 90.4, 23.7],
  ["India", 78.5, 21.5],
  ["Sri Lanka", 80.7, 7.8],
  ["Myanmar", 96.1, 19.7],
  ["Thailand", 101, 15.5],
  ["Laos", 102.6, 19.8],
  ["Vietnam", 106.3, 16.2],
  ["Cambodia", 104.9, 12.6],
  ["Southern China", 109.5, 24],
  ["Philippines", 122.3, 12.5],
  ["Brunei", 114.7, 4.6],
  ["Malaysia", 101.7, 3.6],
  ["Singapore", 103.8, 1.35],
  ["Indonesia", 113.5, -1.5],
  ["Papua New Guinea", 145, -6.3],
].map(([name, lon, lat]) => {
  const [x, y] = projection([lon, lat]);
  return { name, x: Math.round(x), y: Math.round(y) };
});

const out = `// Generated by scripts/build-map.mjs from Natural Earth (public domain). Do not edit by hand.
export const mapSize = { width: ${W}, height: ${H} };
export const landPaths: string[] = ${JSON.stringify(land)};
export const regionPaths: { name: string; d: string }[] = ${JSON.stringify(regions)};
export const mapMarkers: { name: string; x: number; y: number }[] = ${JSON.stringify(markers)};
`;
writeFileSync("src/content/asia-map.ts", out);
console.log("bytes", out.length, "land", land.length, "regions", regions.length);
console.log(markers.map((m) => `${m.name}:${m.x},${m.y}`).join("  "));
